// Compiles the DTCG tokens in /tokens into:
//   src/styles/tokens.css            --ds-* custom properties (semantic ones point at primitives)
//   src/styles/tokens-dark.css       dark mode: the semantic colours in tokens/themes/dark.json,
//                                    applied by the device setting or the visitor's choice
//   src/_data/designTokens.json      flat list the /design-system/ docs and contrast check read
//   src/_data/designTokensDark.json  the same for the dark overrides
import StyleDictionary from 'style-dictionary';

const tierOf = (token) =>
  token.filePath.includes('/themes/')
    ? 'semantic'
    : (['primitive', 'semantic', 'component'].find((tier) =>
        token.filePath.includes(`/${tier}/`),
      ) ?? 'unknown');

const BASE = [
  'tokens/primitive/**/*.json',
  'tokens/semantic/**/*.json',
  'tokens/component/**/*.json',
];
const isDark = (token) => token.filePath.includes('/themes/dark');
const cssValue = (token) => {
  const v = token.original.$value;
  return typeof v === 'string' && /^\{[^}]+\}$/.test(v)
    ? `var(--ds-${v.slice(1, -1).replaceAll('.', '-')})`
    : token.$value;
};

// Dark mode: on when the device is dark (unless the visitor picked Light), or when they
// picked Dark. theme-toggle.js sets <html data-theme="light|dark">.
StyleDictionary.registerFormat({
  name: 'ds/css-dark',
  format: ({ dictionary }) => {
    const vars = dictionary.allTokens
      .filter(isDark)
      .map((t) => `  --${t.name}: ${cssValue(t)};`)
      .join('\n');
    return [
      '/**\n * Generated by scripts/build-tokens.js from tokens/themes/dark.json. Do not edit.\n */',
      ':root {\n  color-scheme: light dark;\n}',
      ':root[data-theme="light"] {\n  color-scheme: light;\n}',
      `:root[data-theme="dark"] {\n  color-scheme: dark;\n\n${vars}\n}`,
      `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n    color-scheme: dark;\n\n${vars.replace(/^/gm, '  ')}\n  }\n}`,
      '',
    ].join('\n\n');
  },
});

StyleDictionary.registerFormat({
  name: 'ds/docs-json',
  format: ({ dictionary }) =>
    JSON.stringify(
      dictionary.allTokens.map((token) => ({
        name: token.name,
        cssVar: `--${token.name}`,
        path: token.path.join('.'),
        tier: tierOf(token),
        type: token.$type,
        value: token.$value,
        alias:
          typeof token.original.$value === 'string' && token.original.$value.startsWith('{')
            ? token.original.$value.slice(1, -1)
            : null,
        description: token.$description ?? token.original.$description ?? null,
      })),
      null,
      2,
    ) + '\n',
});

const config = {
  source: BASE,
  usesDtcg: true,
  log: { verbosity: 'default', warnings: 'error' },
  platforms: {
    css: {
      // Values are authored CSS-ready (rem, clamp(), hex), so only naming transforms run.
      transforms: ['attribute/cti', 'name/kebab'],
      prefix: 'ds',
      buildPath: 'src/styles/',
      files: [
        {
          destination: 'tokens.css',
          format: 'css/variables',
          options: {
            outputReferences: true,
            fileHeader: () => ['Generated by scripts/build-tokens.js from /tokens. Do not edit.'],
          },
        },
      ],
    },
    docs: {
      transforms: ['attribute/cti', 'name/kebab'],
      prefix: 'ds',
      buildPath: 'src/_data/',
      files: [{ destination: 'designTokens.json', format: 'ds/docs-json' }],
    },
  },
};

// The dark theme: the base tokens included, the dark file on top (it overrides by path).
const darkConfig = {
  include: BASE,
  source: ['tokens/themes/dark.json'],
  usesDtcg: true,
  log: { verbosity: 'default', warnings: 'error' },
  platforms: {
    css: {
      transforms: ['attribute/cti', 'name/kebab'],
      prefix: 'ds',
      buildPath: 'src/styles/',
      files: [{ destination: 'tokens-dark.css', format: 'ds/css-dark' }],
    },
    docs: {
      transforms: ['attribute/cti', 'name/kebab'],
      prefix: 'ds',
      buildPath: 'src/_data/',
      files: [{ destination: 'designTokensDark.json', format: 'ds/docs-json', filter: isDark }],
    },
  },
};

/** Builds the token CSS and docs data. Eleventy calls this before every build. */
export async function buildTokens({ quiet = false } = {}) {
  for (const c of [config, darkConfig]) {
    const sd = new StyleDictionary({
      ...c,
      log: { ...c.log, verbosity: quiet ? 'silent' : 'default' },
    });
    await sd.buildAllPlatforms();
  }
}

// Run directly: npm run tokens
if (import.meta.url === `file://${process.argv[1]}`) await buildTokens();
